def _match_tips(filename: str, item: str) -> list[str]:
    meta = GUIDES.get(filename)
    if not meta:
        return ["Открой предмет в JEI (клавиша R) — рецепт и применение.", "Иди по цепочке квестов по порядку."]
    for key, lines in meta.get("keywords", []):
        if key in item:
            return list(lines)
    return list(meta.get("fallback", ["Смотри JEI по предмету.", "Цепочка мастерской идёт слева направо."]))


def build_description(
    filename: str,
    quest_index: int,
    total: int,
    item: str,
    subtitle: str,
    *,
    stage_lab: str = "I",
    stage_name: str = "Старт",
    xp: int = 25,
    reward_item: str = "",
    reward_count: int = 1,
    has_deps: bool = False,
) -> list[str]:
    """FTB description lines (supports & formatting codes)."""
    meta = GUIDES.get(filename, {})
    lines: list[str] = []

    # Header banner
    lines.append(f"&b✦ Мастерская&r  &8·&r  &6Этап {stage_lab}&r &7{stage_name}&r")
    lines.append(f"&8Шаг {quest_index}/{total}&r")
    lines.append("")

    if quest_index == 1 and meta.get("intro"):
        lines.extend(meta["intro"])
        lines.append("")
        lines.append("&8▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬&r")
        lines.append("")

    if has_deps:
        lines.append("&c⛓ Зависимость:&r сначала закрой &eпредыдущий&r квест по стрелке.")
        lines.append("")

    lines.append(f"&a▶ Задача:&r {subtitle}")
    lines.append(f"&7Предмет:&r &f{item}&r")
    lines.append("")
    lines.extend(_match_tips(filename, item))
    lines.append("")
    lines.append("&8▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬▬&r")
    reward_name = reward_item or item
    lines.append(f"&6Награда:&r {reward_count}× {reward_name}  &8+&r  &b{xp} Aqua XP&r")
    lines.append("")
    if quest_index == total:
        lines.append("&d★ Это финал ветки мастерской. Дальше — сюжет или другая мастерская.&r")
    else:
        lines.append("&7Мастерские опциональны: сюжетный spine можно продолжать отдельно.&r")
    return lines


def chapter_subtitle(filename: str, fallback: str) -> str:
    meta = GUIDES.get(filename)
    if meta and meta.get("chapter_subtitle"):
        return meta["chapter_subtitle"]
    return fallback
