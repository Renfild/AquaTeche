    private FishNeighborLines() {
    }

    /** Случайная история, не равная предыдущей; {@code nextInt} возвращает число из [0, bound). */
    public static int pickStory(int size, int last, IntUnaryOperator nextInt) {
        if (size <= 1) {
            return 0;
        }
        int index = nextInt.applyAsInt(size - 1);
        return index >= last && last >= 0 ? index + 1 : index;
    }

    /** Приветствие при подходе: сразу подсказывает, что с ним можно поговорить. */
    public static String greeting(String player, int variant) {
        return switch (Math.floorMod(variant, 3)) {
            case 0 -> "А, " + player + ". Подсаживайся. ПКМ по мне, если хочешь послушать байку.";
            case 1 -> "Здорово, " + player + ". Клюёт вяло, зато компания хорошая. Нажми ПКМ, расскажу что-нибудь.";
            default -> "Тише, " + player + ", не спугни. ПКМ по мне, если не к спеху.";
        };
    }

    public static String heavyCatch(String player, int variant) {
        return switch (Math.floorMod(variant, 3)) {
            case 0 -> "Ого, " + player + ". Покажи-ка эту рыбу.";
            case 1 -> "Тяжёлая, " + player + ". Такую одной левой не вытянешь.";
            default -> player + ", таких я не видел с прошлой весны.";
        };
    }

    /** Комментарий к смене рекорда на стене славы; пустая строка, если рекорда не было. */
    public static String record(FameLogic.Outcome outcome, String player, String previous, String fish, String weight) {
        return switch (outcome) {
            case FIRST -> "На стене занято новое место: " + player + ", " + fish + ", " + weight + ". Посмотрим, кто его отнимет.";
            case TAKEN -> player + " забрал у " + (previous == null ? "кого-то" : previous) + " рыбу вида «" + fish
                    + "»: " + weight + ". Стена пустоты не терпит.";
            case OWN -> player + " побил собственный рекорд: " + fish + ", " + weight + ". С самим собой тоже надо уметь тягаться.";
            case NONE -> "";
        };
    }
